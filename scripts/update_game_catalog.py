"""Rebuild Gavnel's offline Windows catalog from Discord's public game records.

Usage: python scripts/update_game_catalog.py work/detectable-games.json
The input is a reviewable snapshot, never downloaded by the application.
"""
import argparse
from collections import defaultdict
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
REVIEW = json.loads((ROOT / 'scripts/game_catalog_review.json').read_text(encoding='utf-8'))
ORIGINAL = [
    ('Fortnite', 'FortniteClient-Win64-Shipping.exe'),
    ('Valorant', 'VALORANT-Win64-Shipping.exe'),
    ('Rust', 'RustClient.exe'),
    ('Counter-Strike 2', 'cs2.exe'),
]
UTILITY = re.compile(
    r'launcher|setup|install|unins|update|crash|reporter|editor|config|'
    r'server|benchmark|anticheat|battleye|easyanti|helper|redist|'
    r'ragepluginhook|unitycrash|bootstrap|patcher|dotnetfx', re.I)
GENERIC = {'java', 'javaw', 'game', 'launcher', 'client', 'main', 'start',
           'play', 'app', 'application', 'shipping', 'win64', 'win32',
           'ue4game', 'ue5game', 'python', 'pythonw', 'electron', 'nw',
           'flashplayer', 'rundll32', 'chrome', 'msedge', 'firefox',
           'explorer', 'cmd', 'powershell', 'dotnet', 'wscript', 'windows64', 'windows-64bit'}
GENERIC_VARIANT = re.compile(r'^(?:game|client|project|ue4game|ue5game)(?:[-_](?:win|windows|x|dx)?(?:32|64)?(?:[-_]shipping)?)?\.exe$', re.I)
NON_GAME = re.compile(r'\b(?:RPG Maker|FaceRig|creation kit|dedicated server|soundtrack|modeler|final hours|benchmark)\b', re.I)


def basename(record):
    return record.get('name', '').replace('\\', '/').rsplit('/', 1)[-1].lower()


def safe_executable(record):
    name = basename(record)
    return (record.get('os') == 'win32'
            and record.get('is_launcher') is False
            and not record.get('arguments')
            and re.fullmatch(r'[a-z0-9][^/\\<>:*?"|\x00-\x1f]*\.exe', name)
            and name[:-4] not in GENERIC
            and not GENERIC_VARIANT.fullmatch(name)
            and not UTILITY.search(name))


def catalog(records, apply_review=True):
    legacy_names = set(json.loads((ROOT / 'scripts/game_catalog_legacy_names.json').read_text(encoding='utf-8')))
    # Check collisions against ALL applications, including excluded records.
    owners = defaultdict(set)
    for game in records:
        for executable in game.get('executables', []):
            if executable.get('os') == 'win32':
                owners[basename(executable)].add(game['id'])
    entries = {exe.lower(): (name, exe) for name, exe in ORIGINAL}
    for game in records:
        # Require game metadata and a store listing; omit software/unclassified apps.
        if game['name'] not in legacy_names and (not game.get('themes') or not game.get('third_party_skus')):
            continue
        if NON_GAME.search(game['name']) or (apply_review and game['name'] in REVIEW['excluded_titles']):
            continue
        for executable in game.get('executables', []):
            exe = basename(executable)
            if apply_review and exe in REVIEW['excluded_executables']:
                continue
            if safe_executable(executable) and len(owners[exe]) == 1:
                entries.setdefault(exe, (game['name'], exe))
    for alias in REVIEW.get('verified_aliases', []):
        exe = alias['executable'].lower()
        record = dict(name=exe, os='win32', is_launcher=False)
        if not safe_executable(record) or exe in REVIEW['excluded_executables']:
            raise ValueError(f'Unsafe reviewed alias: {exe}')
        if len(owners[exe]) > 1:
            raise ValueError(f'Ambiguous reviewed alias: {exe}')
        if exe in entries and entries[exe][0] != alias['name']:
            raise ValueError(f'Conflicting reviewed alias: {exe}')
        entries[exe] = (alias['name'], exe)
    original_keys = {exe.lower() for _, exe in ORIGINAL}
    additions = [entry for exe, entry in entries.items() if exe not in original_keys]
    return ORIGINAL + sorted(additions, key=lambda entry: (entry[0].casefold(), entry[1]))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('snapshot', type=Path)
    args = parser.parse_args()
    records = json.loads(args.snapshot.read_text(encoding='utf-8-sig'))
    entries = catalog(records)
    lines = ['// Generated by scripts/update_game_catalog.py; do not edit.',
             '// Source and filtering policy: docs/game-detection.md',
             'pub(crate) const OFFICIAL_GAMES: &[(&str, &str)] = &[']
    # JSON's ASCII string escapes differ from Rust's; keep Unicode literal.
    for name, exe in entries:
        lines.append(f'    ({json.dumps(name, ensure_ascii=False)}, {json.dumps(exe, ensure_ascii=False)}),')
    lines.append('];')
    lines.append('pub(crate) const RETIRED_GAMES: &[(&str, &str)] = &[')
    for name, exe in sorted(set(catalog(records, apply_review=False)) - set(entries)):
        lines.append(f'    ({json.dumps(name, ensure_ascii=False)}, {json.dumps(exe, ensure_ascii=False)}),')
    lines.append('];')
    output = ROOT / 'src/config/game_catalog_data.rs'
    output.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    print(f'{len(set(name for name, _ in entries)):,} titles; {len(entries):,} executable aliases')


if __name__ == '__main__':
    main()
